/**
 * Extracts comprehensive vocabulary hints from passage text using the language dictionary.
 * Supports inflections, compounds, and CJK substring scanning across the entire passage.
 */
export function extractDictionaryVocabulary(
  passage: string,
  languageCode: string,
  minTerms = 12,
  maxTerms = 500
): Record<string, string> {
  const lang = MultilingualLemmatizer.normalizeLanguageCode(languageCode);
  const baseDict = MULTILINGUAL_DICTIONARY[lang] || MULTILINGUAL_DICTIONARY['de'];
  const expandedDict = EXPANDED_READING_DICTIONARY[lang] || {};
  const dict: Record<string, string> = { ...expandedDict, ...baseDict };
  const extracted: Record<string, string> = {};

  if (!passage || typeof passage !== 'string') {
    return extracted;
  }

  const cleanPassage = passage.toLowerCase();
  const punctRegex = /[.,!?:;()„“"»«[\]/|\\—–\s]/g;

  // 1. First pass: direct substring / word boundary scanning against dictionary terms
  const dictKeys = Object.keys(dict).sort((a, b) => b.length - a.length);

  for (const term of dictKeys) {
    if (Object.keys(extracted).length >= maxTerms) break;

    const cleanTerm = term.toLowerCase().trim();
    if (cleanTerm.length < 2) continue;

    if (['zh', 'ja'].includes(lang)) {
      // Direct character substring match
      if (cleanPassage.includes(cleanTerm)) {
        extracted[cleanTerm] = dict[term];
      }
    } else {
      // Word boundary match for alphabetic languages
      const regex = new RegExp(`(^|[\\s.,!?:;()„“"»«[\\-\\/])${cleanTerm}($|[\\s.,!?:;()„“"»«[\\-\\/])`, 'i');
      if (regex.test(cleanPassage)) {
        extracted[cleanTerm] = dict[term];
      } else if (cleanTerm.length >= 5) {
        // Stem match (e.g. inflected verbs/plurals: wohnen -> wohne, kinder -> kindern)
        const stem = cleanTerm.slice(0, -1);
        if (cleanPassage.includes(stem)) {
          extracted[cleanTerm] = dict[term];
        }
      }
    }
  }

  // 2. Second pass: Scan all passage tokens across the entire text against candidate lemmas, dictionary stems, and compounds
  if (!['zh', 'ja'].includes(lang)) {
    const tokens = cleanPassage.split(/[\s,.;:!?()„“"»«[\]/|\\—–-]+/).map(t => t.replace(punctRegex, '').trim()).filter(t => t.length >= 3);
    for (const tok of tokens) {
      if (Object.keys(extracted).length >= maxTerms) break;
      if (extracted[tok]) continue;

      // Check candidate lemmas first (exact morphological rules)
      const candidates = MultilingualLemmatizer.getCandidateLemmas(tok, lang);
      let matched = false;
      for (const cand of candidates) {
        if (dict[cand]) {
          extracted[tok] = dict[cand];
          matched = true;
          break;
        }
      }
      if (matched || tok.length < 4) continue;

      for (const dictKey of dictKeys) {
        if (dictKey.length >= 4 && (
          tok === dictKey ||
          tok.startsWith(dictKey) ||
          dictKey.startsWith(tok) ||
          (tok.length >= 7 && dictKey.length >= 5 && tok.endsWith(dictKey))
        )) {
          extracted[tok] = dict[dictKey];
          break;
        }
      }
    }
  }

  // 3. Third pass: Guarantee minimum word count from thematic dictionary pool when requested
  if (minTerms > 0 && Object.keys(extracted).length < minTerms) {
    for (const term of dictKeys) {
      if (Object.keys(extracted).length >= minTerms) break;
      if (!extracted[term]) {
        extracted[term] = dict[term];
      }
    }
  }

  return extracted;
}

