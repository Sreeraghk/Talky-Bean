export class LocalizationService {
  /**
   * Retrieves the current native language code selected by the user.
   * Defaults to 'en' (English).
   */
  static getNativeLanguage(): string {
    return StorageService.load<string>('native_language', undefined, 'en');
  }

  /**
   * Translates a given UI key into the current selected native language.
   * Falls back to English if translation is missing.
   */
  static t(key: string): string {
    const lang = this.getNativeLanguage();
    const group = translations[lang] || translations['en'];
    return group[key] || translations['en'][key] || key;
  }

  /**
   * Translates a given UI key to a specific language code.
   */
  static tTo(key: string, langCode: string): string {
    const group = translations[langCode] || translations['en'];
    return group[key] || translations['en'][key] || key;
  }

  /**
   * Formats local native and target language names.
   */
  static getNativeName(code: string): string {
    return NATIVE_LANGUAGE_NAMES[code] || code.toUpperCase();
  }

  /**
   * Returns flag icon of selected language.
   */
  static getFlag(code: string): string {
    return NATIVE_LANGUAGE_FLAGS[code] || '🌐';
  }
}
