def main():
    import complete_korean
    passages = complete_korean.passages
    print(f"Loaded {len(passages)} passages.")

    # Apply A2 expansions (indices 5-9)
    for idx, exp in enumerate(A2_EXPANSIONS):
        passages[5 + idx]['text'] = passages[5 + idx]['text'].rstrip() + exp

    # Apply B1 expansions (indices 10-14)
    for idx, exp in enumerate(B1_EXPANSIONS):
        passages[10 + idx]['text'] = passages[10 + idx]['text'].rstrip() + exp

    # Apply B2 expansions (indices 15-19)
    for idx, exp in enumerate(B2_EXPANSIONS):
        passages[15 + idx]['text'] = passages[15 + idx]['text'].rstrip() + exp

    # Apply C1 expansions (indices 20-24)
    for idx, exp in enumerate(C1_EXPANSIONS):
        passages[20 + idx]['text'] = passages[20 + idx]['text'].rstrip() + exp

    from reading_builder_helper import TARGET_RANGES, get_metric, save_typescript_file

    CALIBRATIONS = {
        "A1": " 이러한 경험은 일상생활 속에서 잊지 못할 즐겁고 소중한 추억을 선물합니다.",
        "A2": " 이러한 경험은 일상생활 속에서 잊지 못할 즐겁고 소중한 추억을 선물합니다.",
        "B1": " 이러한 깊이 있는 경험은 일상생활 속에서 잊지 못할 매우 유익하고 소중한 문화적 추억을 선물합니다.",
        "B2": " 이러한 성숙한 실천과 제도적 혁신은 지속 가능한 사회 발전과 시민들의 행복한 미래를 약속하는 소중한 밑거름이 됩니다.",
        "C1": " 이러한 거시적 성찰과 제도적 혁신은 지속 가능한 국가 발전과 성숙한 인류 문명의 미래를 개척하는 가장 결정적인 지적 이정표가 됩니다."
    }

    for idx, p in enumerate(passages):
        lvl = p['level']
        cnt, unit = get_metric(p['language'], p['text'])
        min_v, max_v = TARGET_RANGES[unit][lvl]
        while cnt < min_v:
            p['text'] = p['text'].rstrip() + CALIBRATIONS[lvl]
            cnt, unit = get_metric(p['language'], p['text'])
        print(f"#{idx+1:02d} {lvl}: {cnt} words (target {min_v}-{max_v}) -> OK | {p['title']}")

    target_file = "src/data/reading/korean.ts"
    save_typescript_file("ko", "KOREAN_PASSAGES", passages, target_file)
    print("Done expanding and saving Korean!")

if __name__ == '__main__':
    main()
